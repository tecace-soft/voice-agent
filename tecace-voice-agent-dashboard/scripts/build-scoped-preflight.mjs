// Writes src/styles/ui-preflight.css: Tailwind's reset, scoped to `.tw` subtrees.
//
// Run after upgrading tailwindcss:  npm run gen:preflight
// (tests/styles.test.ts fails while the committed file is out of date.)
//
// Why scoped: the transcribe screens were written against browser defaults, and a global reset
// changes them (heading sizes, margins, buttons, list bullets). Promo screens were written against
// the reset. Wrapping it in @scope (.tw) gives each side the ground it was built on.
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

// preflight's `html, :host { … }` rule can't match inside a scope; `:scope` stands in for it.
const ROOT_OPENER = /html,\s*:host\s*\{/g;

// Then one addition on top of preflight's root rule: the promo font, without going through
// Tailwind's --default-font-family (kept as its own rule so the preflight copy stays verbatim).
const rootOverride = `
  :scope {
    font-family: var(--ui-font-sans);
  }
`;

// The transcribe CSS styles some elements with bare selectors (a:hover, code, table, th, td,
// :focus-visible). The comment emitted below explains the rule; the browser default it reverts to
// is what the promo app had.
const undoLegacy = `
  /* Undo the transcribe CSS's bare element rules inside .tw. preflight already wins for every
     property it sets; this block reverts only what it doesn't (to the browser default). */
  a:hover { text-decoration: inherit; }
  code {
    background: revert;
    color: revert;
    border-radius: revert;
  }
  table { width: revert; }
  th, td {
    text-align: revert;
    height: revert;
    vertical-align: revert;
    white-space: revert;
    color: revert;
    font-weight: revert;
    font-size: revert;
    line-height: revert;
    letter-spacing: revert;
    background: revert;
    font-variant-numeric: revert;
  }
  /* outline-color is left alone: the promo \`*\` rule (ui-theme.css) sets it. */
  :where(button, a, input, select):focus-visible {
    outline-style: revert;
    outline-width: revert;
    outline-offset: revert;
  }
`;

/** Pure: preflight.css text + tailwindcss version -> the ui-preflight.css text. */
export function buildScopedPreflight(preflightCss, version) {
  const matches = preflightCss.match(ROOT_OPENER) ?? [];
  if (matches.length !== 1) {
    throw new Error(
      `build-scoped-preflight: expected exactly one "html, :host {" rule in tailwindcss@${version} ` +
        `preflight.css, found ${matches.length}. Preflight changed — update the script.`,
    );
  }
  const scoped = preflightCss.replace(ROOT_OPENER, ":scope {");

  const header = `/* GENERATED by scripts/build-scoped-preflight.mjs from tailwindcss@${version} preflight.css.
   Do not edit by hand — run \`npm run gen:preflight\` instead.

   Imported into @layer base, which sits AFTER @layer legacy (the transcribe CSS). So inside a .tw
   subtree this reset beats the transcribe rules; outside one it matches nothing. */
`;
  return `${header}@scope (.tw) {\n${scoped}\n${rootOverride}\n${undoLegacy}}\n`;
}

function main() {
  const require = createRequire(import.meta.url);
  const root = join(dirname(fileURLToPath(import.meta.url)), "..");
  const preflight = readFileSync(require.resolve("tailwindcss/preflight.css", { paths: [root] }), "utf8");
  const { version } = JSON.parse(
    readFileSync(require.resolve("tailwindcss/package.json", { paths: [root] }), "utf8"),
  );
  const out = buildScopedPreflight(preflight, version);
  writeFileSync(join(root, "src", "styles", "ui-preflight.css"), out);
  console.log(`wrote src/styles/ui-preflight.css (tailwindcss@${version}, ${out.length} bytes)`);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
